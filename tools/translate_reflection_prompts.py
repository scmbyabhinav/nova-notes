#!/usr/bin/env python3
"""Generate offline ORAH reflection prompt translations once during CI."""
import json
import re
import time
import urllib.parse
import urllib.request
from pathlib import Path

SOURCE = Path("lib/services/prompt_service.dart")
OUTPUT = Path("lib/data/reflection_prompt_translations.dart")
LOCALES = ["ar", "de", "es", "fr", "he", "hi", "id", "it", "ja", "ko", "pt", "tr", "zh"]

def extract_prompts(source):
    pattern = re.compile(r"ReflectionPrompt\(text:\s*(['\"])(.*?)\1,\s*category:\s*(['\"])(.*?)\3\)", re.S)
    prompts = []
    for match in pattern.finditer(source):
        raw = match.group(2)
        quote = match.group(1)
        text = raw.replace("\\\\", "\\")
        if quote == "'":
            text = text.replace("\\'", "'")
        else:
            text = text.replace('\\"', '"')
        prompts.append(text)
    if len(prompts) != 150:
        raise SystemExit(f"Expected exactly 150 prompts, found {len(prompts)}")
    return prompts

def translate(text, locale):
    url = "https://translate.googleapis.com/translate_a/single?" + urllib.parse.urlencode({
        "client": "gtx", "sl": "en", "tl": locale, "dt": "t", "q": text
    })
    request = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 ORAH-localization-generator"})
    last_error = None
    for attempt in range(4):
        try:
            with urllib.request.urlopen(request, timeout=25) as response:
                data = json.loads(response.read().decode("utf-8"))
            result = "".join(part[0] for part in data[0] if part and part[0])
            if not result.strip():
                raise ValueError("empty translation")
            return result
        except Exception as error:
            last_error = error
            time.sleep(1.5 * (attempt + 1))
    raise RuntimeError(f"Translation failed for locale {locale}: {last_error}")

